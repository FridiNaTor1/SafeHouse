#!/usr/bin/env python3
"""Embeds files as C++ byte arrays for the Switch build (cmake/Switch.cmake).

    switch_embed.py OUTPUT.h SYMBOL INPUT [SYMBOL INPUT ...]

Each SYMBOL becomes `inline const unsigned char SYMBOL[] = {...};` (the same form as cmake/embed-image.cmake, which is
far slower on large files). The output is only rewritten when its contents change, so unchanged assets recompile
nothing.
"""
import os
import sys


def main():
    if len(sys.argv) < 4 or len(sys.argv) % 2 != 0:
        sys.exit(__doc__)
    output = sys.argv[1]
    lines = ['#pragma once', '// Generated by cmake/switch_embed.py: do not edit.']
    for symbol, path in zip(sys.argv[2::2], sys.argv[3::2]):
        with open(path, 'rb') as f:
            data = f.read()
        lines.append(f'inline const unsigned char {symbol}[] = {{')
        for i in range(0, len(data), 32):
            lines.append(','.join(str(b) for b in data[i:i + 32]) + ',')
        if not data:
            lines.append('0')
        lines.append('};')
        lines.append(f'inline constexpr unsigned long {symbol}_size = {len(data)}ul;')
    text = '\n'.join(lines) + '\n'
    if os.path.exists(output):
        with open(output, 'r', encoding='utf-8') as f:
            if f.read() == text:
                return
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    with open(output, 'w', encoding='utf-8') as f:
        f.write(text)


if __name__ == '__main__':
    main()
